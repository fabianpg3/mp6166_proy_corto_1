`ifndef MULT_INTERFACE
`define MULT_INTERFACE

interface mult_interface(input logic clk,reset);
  
  ////////////////////////////////////////////////////////////////////////////
  // Declaration of Signals
  ////////////////////////////////////////////////////////////////////////////
  logic [63:0] x,y;
  logic [127:0] result;
  ////////////////////////////////////////////////////////////////////////////
  // clocking block and modport declaration for driver 
  ////////////////////////////////////////////////////////////////////////////
  clocking dr_cb@(posedge clk) ;
    output x; 
    output y;
    input  result;
  endclocking
  
  modport DRV (clocking dr_cb,input clk,reset) ;

  ////////////////////////////////////////////////////////////////////////////
  // clocking block and modport declaration for monitor 
  ////////////////////////////////////////////////////////////////////////////
  clocking rc_cb@(negedge clk) ;
    input x; 
    input y;
    input result;
  endclocking
  
  modport RCV (clocking rc_cb,input clk,reset);

endinterface

`endif
