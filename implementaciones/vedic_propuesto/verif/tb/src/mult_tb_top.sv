`ifndef MULT_TB_TOP
`define MULT_TB_TOP
 `include "uvm_macros.svh"
`include "mult_interface.sv"
import uvm_pkg::*;
module mult_tb_top;
   
 
  import mult_test_list::*;

  //////////////////////////////////////////////////////////////////////////////
  // Declaration of Local Fields
  //////////////////////////////////////////////////////////////////////////////
  parameter cycle = 10 ;
  bit clk;
  bit reset;
  int clock_counter;
  //////////////////////////////////////////////////////////////////////////////
  //clock generation
  //////////////////////////////////////////////////////////////////////////////
  initial begin
     clk=0;
     clock_counter = 0;
     forever #(cycle/2) clk=~clk;
  end

  always @(posedge clk) begin
    if (reset == 0) begin
      clock_counter = clock_counter + 1;
    end
  end
  //////////////////////////////////////////////////////////////////////////////
  //reset Generation : change may required while generating reset for 
  //                   synchronous/Asynchronous or Active low/Active high
  //////////////////////////////////////////////////////////////////////////////
  initial begin
    reset = 1;  
    #(cycle* 5) reset =0;
  end
  //////////////////////////////////////////////////////////////////////////////
  //creatinng instance of interface, inorder to connect DUT and testcase
  //////////////////////////////////////////////////////////////////////////////
  mult_interface mult_intf(clk,reset);
  
  //////////////////////////////////////////////////////////////////////////////
  /*********************mult DUT Instantation **********************************/
  //////////////////////////////////////////////////////////////////////////////

  vedic_mult_64x64_param_pipeline dut_inst(
    .clk(clk),
    .op_a(mult_intf.x),
		.op_b(mult_intf.y),
    .mult_res(mult_intf.result)
  );

  //vedic_mult_64x64_param dut_inst(
  //  .op_a(mult_intf.x),
	//	.op_b(mult_intf.y),
  //  .mult_res(mult_intf.result)
  //);


  
  //////////////////////////////////////////////////////////////////////////////
  /*********************starting the execution uvm phases**********************/
  //////////////////////////////////////////////////////////////////////////////
  initial begin
    run_test();
  end
  //////////////////////////////////////////////////////////////////////////////
  /**********Set the Interface instance Using Configuration Database***********/
  //////////////////////////////////////////////////////////////////////////////
  initial begin
   uvm_config_db#(virtual mult_interface)::set(uvm_root::get(),"*","intf",mult_intf);
  end

endmodule

`endif



